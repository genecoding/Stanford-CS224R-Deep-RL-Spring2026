_secrets = [modal.Secret.from_name("wandb-secret")]  # use the same name as hw2


@app.function(
    image=image,
    volumes={"/root/hw/data": volume},
    secrets=_secrets,
    gpu="T4",
    timeout=14400,
)
def train(algo, env_name, exp_name, extra_args):
    import os
    import subprocess
    import shutil  # add this

    os.chdir("/root/hw")

    # Install the local cs224r package so imports resolve.
    subprocess.run(["pip", "install", "-e", "."], check=True)

    cmd = [
        "python", "cs224r/scripts/run_algo.py",
        "--algo", algo,
        "--env_name", env_name,
        "--exp_name", exp_name,
    ] + extra_args

    # subprocess.run(cmd, check=True)

    ##########
    # add this: save the output to the corresponding directory as output.log
    # define a temp log file path
    data_path = '/root/hw/data'
    os.makedirs(data_path, exist_ok=True)
    temp_log_path = os.path.join(data_path, f'temp_{exp_name}.log')
    
    # run training and redirect both stdout and stderr to the temp file
    with open(temp_log_path, 'w') as f:
        subprocess.run(cmd, check=True, stdout=f, stderr=subprocess.STDOUT)
    
    # # convert the command list into a single space-separated string so the shell can interpret it
    # # '2>&1' redirects stderr into stdout so they are merged
    # # '| tee' splits the merged stream, sending it to both the console and the temp file
    # cmd_str = ' '.join(cmd) + f' 2>&1 | tee {temp_log_path}'
    
    # # use 'shell=True' to enable shell features like piping (|) and redirection (2>&1)
    # subprocess.run(cmd_str, shell=True, check=True)
    
    # parse the temp log to extract the exact runtime log directory generated by run_algo.py
    target_dir = None
    with open(temp_log_path, 'r') as f:
        for line in f:
            if 'LOGGING TO:' in line:
                # extract the absolute path trailing 'LOGGING TO:' and strip any whitespace or newline
                target_dir = line.split('LOGGING TO:')[1].strip()
                break
            
    # rename and move the temp log to the corresponding output directory
    if target_dir and os.path.isdir(target_dir):
        final_log_path = os.path.join(target_dir, 'output.log')
        shutil.move(temp_log_path, final_log_path)
    #     print(f'[{exp_name}] Success! Log file successfully moved to: {final_log_path}')
    # else:
    #     # keep the temp file in place if the folder wasn't found
    #     print(f'[{exp_name}] Warning: Could not resolve the exact log directory from the output. Temp log preserved.')
    ##########

    # Flush volume writes so results survive after the container shuts down.
    volume.commit()
